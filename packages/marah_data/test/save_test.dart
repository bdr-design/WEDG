import 'dart:convert';
import 'dart:io';

import 'package:marah_data/marah_data.dart';
import 'package:marah_domain/marah_domain.dart';
import 'package:marah_domain/testing.dart';
import 'package:test/test.dart';

Game sampleGame() {
  final g = Game.create(
    seed: 1,
    playerName: 'اختبار',
    farmName: 'عزبة الاختبار',
    region: Region.hail,
    favourite: ColorCategory.wodh,
  );
  final bot = Bot(g);
  for (var i = 0; i < 8; i++) {
    bot.week();
  }
  return g;
}

/// Saves written by released versions. They must load forever: if this
/// test fails, add a migration instead of editing the fixture.
/// (Before the first public release the v1 fixture may still be
/// regenerated by deleting it; see docs/adr/0003-save-format.md.)
const fixtures = {1: 'test/fixtures/save_v1.json'};

void main() {
  const codec = SaveCodec();

  test('round trip is exact', () {
    final g = sampleGame();
    final text = codec.encode(g.state, savedAt: DateTime.utc(2026));
    final loaded = codec.decode(text) as Loaded;
    expect(jsonEncode(loaded.state.toJson()), jsonEncode(g.state.toJson()));
  });

  for (final MapEntry(key: version, value: path) in fixtures.entries) {
    test('save written by version $version still loads', () {
      final file = File(path);
      if (!file.existsSync()) {
        // First run creates the fixture for the current version.
        if (version != SaveCodec.currentVersion) {
          fail('missing fixture for old version $version');
        }
        file
          ..createSync(recursive: true)
          ..writeAsStringSync(
            codec.encode(sampleGame().state, savedAt: DateTime.utc(2026)),
          );
      }
      final result = codec.decode(file.readAsStringSync());
      expect(result, isA<Loaded>(), reason: '$result');
      final state = (result as Loaded).state;
      expect(checkInvariants(state), isEmpty);
      // It must still play.
      final g = Game(state)..advanceDays(30);
      expect(checkInvariants(g.state), isEmpty);
    });
  }

  group('rejects without losing anything', () {
    test('garbage', () {
      expect(codec.decode('not json'), isA<LoadFailed>());
      expect(codec.decode('{"a":1}'), isA<LoadFailed>());
    });

    test('a save from a newer app', () {
      final r = codec.decode(
        jsonEncode({
          'format': SaveCodec.format,
          'version': SaveCodec.currentVersion + 1,
          'data': <String, Object?>{},
        }),
      ) as LoadFailed;
      expect(r.problem, LoadProblem.tooNew);
    });

    test('broken data inside a valid envelope', () {
      final r = codec.decode(
        jsonEncode({
          'format': SaveCodec.format,
          'version': SaveCodec.currentVersion,
          'data': {'world': 1},
        }),
      ) as LoadFailed;
      expect(r.problem, LoadProblem.corrupt);
    });
  });

  group('SaveStore', () {
    test('a broken save is backed up and never overwritten', () async {
      final backend = MemoryBackend()..data['marah.save'] = '{broken';
      final store = SaveStore(backend);
      expect(await store.open(), isA<OpenFailed>());
      expect(backend.data['marah.save.broken'], '{broken');
      await store.save(sampleGame().state);
      await store.flush();
      expect(backend.data['marah.save'], '{broken');
    });

    test('keeps the previous good save', () async {
      final backend = MemoryBackend();
      final store = SaveStore(backend);
      final g = sampleGame();
      await store.save(g.state);
      g.advanceDays(3);
      await store.save(g.state);
      await store.flush();
      expect(backend.data['marah.save.prev'], isNotNull);
      final prev = await store.openPrevious() as Opened;
      expect(prev.state.world.day, g.today - 3);
    });

    test('start over clears the slot but keeps the broken backup', () async {
      final backend = MemoryBackend()..data['marah.save'] = '{broken';
      final store = SaveStore(backend);
      await store.open();
      await store.startOver();
      expect(await store.open(), isA<NoSave>());
      expect(backend.data['marah.save.broken'], '{broken');
      await store.save(sampleGame().state);
      await store.flush();
      expect(await store.open(), isA<Opened>());
    });
  });
}
