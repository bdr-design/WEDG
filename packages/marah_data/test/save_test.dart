import 'dart:convert';
import 'dart:io';

import 'package:marah_data/marah_data.dart';
import 'package:marah_domain/marah_domain.dart';
import 'package:marah_domain/testing.dart';
import 'package:test/test.dart';

Game sampleGame() {
  final g = Game.create(
    seed: 1,
    playerName: 'اختبار',
    farmName: 'عزبة الاختبار',
    region: Region.hail,
    favourite: ColorCategory.wodh,
    startedAt: DateTime.utc(2026, 11, 8),
  );
  final bot = Bot(g);
  for (var i = 0; i < 8; i++) {
    bot.week();
  }
  return g;
}

/// Saves written by released versions. They must load forever: if this
/// test fails, add a migration instead of editing the fixture.
/// (Before the first public release the v1 fixture may still be
/// regenerated by deleting it; see docs/adr/0003-save-format.md.)
const fixtures = {
  1: 'test/fixtures/save_v1.json',
  2: 'test/fixtures/save_v2.json',
};

void main() {
  const codec = SaveCodec();

  test('round trip is exact', () {
    final g = sampleGame();
    final text = codec.encode(g.state, savedAt: DateTime.utc(2026));
    final loaded = codec.decode(text) as Loaded;
    expect(jsonEncode(loaded.state.toJson()), jsonEncode(g.state.toJson()));
  });

  for (final MapEntry(key: version, value: path) in fixtures.entries) {
    test('save written by version $version still loads', () {
      final file = File(path);
      if (!file.existsSync()) {
        // Fixtures are created on purpose only, never by a passing test.
        if (Platform.environment['MARAH_WRITE_FIXTURES'] != '1') {
          fail(
            'missing fixture $path (set MARAH_WRITE_FIXTURES=1 to create '
            'one for the current version)',
          );
        }
        if (version != SaveCodec.currentVersion) {
          fail('missing fixture for old version $version');
        }
        file
          ..createSync(recursive: true)
          ..writeAsStringSync(
            codec.encode(sampleGame().state, savedAt: DateTime.utc(2026)),
          );
      }
      final result = codec.decode(file.readAsStringSync());
      expect(result, isA<Loaded>(), reason: '$result');
      final state = (result as Loaded).state;
      expect(checkInvariants(state), isEmpty);
      // It must still play.
      final g = Game(state)..advanceDays(30);
      expect(checkInvariants(g.state), isEmpty);
    });
  }

  test(
    'v1 to v2: مغاتير becomes وضح, حق and لقي swap, mature becomes فاطر',
    () {
      final raw = jsonDecode(
        File(fixtures[1]!).readAsStringSync(),
      ) as Map<String, Object?>;
      final before = jsonEncode(raw['data']);
      final after = jsonEncode(
        SaveCodec.migrations[1]!(raw['data']! as Map<String, Object?>),
      );
      int n(String text, String pattern) => pattern.allMatches(text).length;
      expect(n(before, '"cat":"maghateer"'), greaterThan(0));
      expect(after.contains('maghateer'), isFalse);
      expect(
        n(after, '"cat":"wodh"'),
        n(before, '"cat":"wodh"') + n(before, '"cat":"maghateer"'),
      );
      expect(n(after, '"age":"haq"'), n(before, '"age":"laqi"'));
      expect(n(after, '"age":"laqi"'), n(before, '"age":"haq"'));
      expect(n(after, '"age":"fater"'), n(before, '"age":"mature"'));
      expect(after.contains('"age":"mature"'), isFalse);
      // ledger categories (also under "cat") are left alone
      expect(n(after, '"cat":"feed"'), n(before, '"cat":"feed"'));
    },
  );

  group('rejects without losing anything', () {
    test('garbage', () {
      expect(codec.decode('not json'), isA<LoadFailed>());
      expect(codec.decode('{"a":1}'), isA<LoadFailed>());
    });

    test('a save from a newer app', () {
      final r = codec.decode(
        jsonEncode({
          'format': SaveCodec.format,
          'version': SaveCodec.currentVersion + 1,
          'data': <String, Object?>{},
        }),
      ) as LoadFailed;
      expect(r.problem, LoadProblem.tooNew);
    });

    test('broken data inside a valid envelope', () {
      final r = codec.decode(
        jsonEncode({
          'format': SaveCodec.format,
          'version': SaveCodec.currentVersion,
          'data': {'world': 1},
        }),
      ) as LoadFailed;
      expect(r.problem, LoadProblem.corrupt);
    });
  });

  group('SaveStore', () {
    test('a broken save is backed up and never overwritten', () async {
      final backend = MemoryBackend()..data['marah.save'] = '{broken';
      final store = SaveStore(backend);
      expect(await store.open(), isA<OpenFailed>());
      expect(backend.data['marah.save.broken'], '{broken');
      await store.save(sampleGame().state);
      await store.flush();
      expect(backend.data['marah.save'], '{broken');
    });

    test('the fallback is the last save proven good, and restores', () async {
      final backend = MemoryBackend();
      final store = SaveStore(backend);
      final g = sampleGame();
      await store.save(g.state);
      expect(backend.data['marah.save.prev'], isNull);
      final good = backend.data['marah.save'];
      final opened = SaveStore(backend);
      expect(await opened.open(), isA<Opened>());
      // Only a save the engine proved good becomes the fallback.
      expect(backend.data['marah.save.prev'], isNull);
      expect(await opened.markGood(), isTrue);
      expect(backend.data['marah.save.prev'], good);

      backend.data['marah.save'] = '{broken';
      final again = SaveStore(backend);
      expect(await again.open(), isA<OpenFailed>());
      final restored = await again.openPrevious() as Opened;
      expect(restored.state.world.day, g.today);
      expect(backend.data['marah.save'], good);
      expect(again.locked, isFalse);
    });

    test('one failed write does not stop later writes', () async {
      final backend = _FlakyBackend();
      final store = SaveStore(backend);
      final g = sampleGame();
      backend.failNext = true;
      await expectLater(store.save(g.state), throwsA(isA<StateError>()));
      await store.save(g.state);
      await store.flush();
      expect(backend.data['marah.save'], isNotNull);
    });

    test('unreadable bytes are backed up and saving is locked', () async {
      final backend = _FlakyBackend()..data['marah.save'] = 'x';
      backend.failReads = true;
      final store = SaveStore(backend);
      expect(await store.open(), isA<OpenFailed>());
      expect(backend.data['marah.save.broken'], 'x');
      await store.save(sampleGame().state);
      expect(backend.data['marah.save'], 'x');
    });

    test('start over clears the slot but keeps the broken backup', () async {
      final backend = MemoryBackend()..data['marah.save'] = '{broken';
      final store = SaveStore(backend);
      await store.open();
      await store.startOver();
      expect(await store.open(), isA<NoSave>());
      expect(backend.data['marah.save.broken'], '{broken');
      await store.save(sampleGame().state);
      await store.flush();
      expect(await store.open(), isA<Opened>());
    });
  });
}

class _FlakyBackend extends MemoryBackend {
  bool failNext = false;
  bool failReads = false;

  @override
  Future<void> write(String key, String value) async {
    if (failNext) {
      failNext = false;
      throw StateError('disk full');
    }
    await super.write(key, value);
  }

  @override
  Future<String?> read(String key) async {
    if (failReads) throw const FormatException('bad utf-8');
    return super.read(key);
  }
}
