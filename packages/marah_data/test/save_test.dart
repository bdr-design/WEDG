Game sampleGame() {
  final g = Game.create(
    seed: 1,
    playerName: 'اختبار',
    farmName: 'عزبة الاختبار',
    region: Region.hail,
    favourite: ColorCategory.wodh,
    startedAt: DateTime.utc(2026, 11, 8),
  );
  final bot = Bot(g);
  for (var i = 0; i < 8; i++) {
    bot.week();
  }
  // orders on their way, a small tanker's among them (sizes kept since v6)
  g.me.farm.waterL = g.me.farm.tankL - 6000.0;
  g.dispatch(OrderSupply(g.me.id, Supply.water, 1, tanker: Tanker.small));
  g.dispatch(OrderSupply(g.me.id, Supply.barley, 2));
  // a facility being built and the calves' share of the milk (since v7)
  g.dispatch(SetCalfShare(g.me.id, CalfShare.quarter));
  g.dispatch(BuildFacility(g.me.id, Facility.pen));
  // an entry, a secret treatment and a ban (since v8)
  grant(g, 100000);
  final f = g.state.world.festivals.values.firstWhere((f) => !f.done);
  g.advanceTo(f.opensOn);
  final r = f.rounds.firstWhere((r) => r.kind == RoundKind.mafareed);
  final sim = Sim(g.state);
  final c = WorldGen(sim).makeCamel(
    sim.rng(['fixture']),
    owner: g.me.id,
    mean: 70,
    category: r.category,
    sex: r.sex,
    ageDays: AgeClass.mafrood.minDays + 100 - r.day.daysSince(g.today),
  )..acquiredOn = g.today - 100;
  final ok = g.dispatch(EnterRound(g.me.id, f.id, r.id, [c.id])).ok;
  if (!ok) throw StateError('the fixture camel did not enter');
  g.dispatch(Tamper(g.me.id, c.id, TamperKind.dye, 2));
  final rival = g.state.world.owners.keys.first;
  g.state.world.bans[rival] = 2031;
  // a treated listing looked at by his vet, found, and bought knowing
  // (since v12)
  {
    final l = g.state.world.listings.values.firstWhere(
      (x) => !g.state.players.containsKey(x.sellerId),
    );
    final bought = g.state.world.camels[l.camelId]!;
    bought.treatments.add(
      Tampering(
        kind: TamperKind.dye,
        strength: 1,
        on: g.today,
        until: g.today + 29,
        by: l.sellerId,
        knownBy: [g.me.id],
      ),
    );
    grant(g, l.askPrice.value + 10000);
    if (!g.dispatch(BuyListing(g.me.id, l.id)).ok) {
      throw StateError('the fixture listing was not bought');
    }
  }
  // the secret treatment man's message (the entry above sent it) and a
  // finding not yet told (since v9)
  g.me.untold.add(
    Finding(
      camel: c.id,
      name: c.name,
      kind: TamperKind.dye,
      fine: 0,
      knew: false,
      day: g.today,
    ),
  );
  return g;
}

/// Saves written by released versions. They must load forever: if this
