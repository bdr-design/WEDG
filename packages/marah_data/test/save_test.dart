    expect(cs['calf']!['crossbred'], isFalse); // مغاتير x وضح: both وضح now
    expect(cs['calf']!['cat'], 'wodh');
    expect(cs['mixed']!['crossbred'], isTrue); // وضح x حمر still crossbred
    final ages = [
      for (final e in (out['inboxes']! as Map)['p']! as List) (e as Map)['age'],
    ];
    expect(ages, ['fater', 'naab', 'harish', 'fater', 'makhlool', 'hwar']);
  });

  test('v2 to v3: the legs split into the forehand and the hindquarters', () {
    final raw = jsonDecode(
      File(fixtures[2]!).readAsStringSync(),
    ) as Map<String, Object?>;
    final before = raw['data']! as Map<String, Object?>;
    final after = SaveCodec.migrations[2]!(before);
    List<Map<String, Object?>> camels(Map<String, Object?> d) =>
        ((d['world']! as Map)['camels']! as List).cast<Map<String, Object?>>();
    final b = camels(before), a = camels(after);
    expect(a.length, b.length);
    for (var i = 0; i < a.length; i++) {
      for (final k in ['genes', 'env']) {
        final old = b[i][k]! as List, now = a[i][k]! as List;
        expect(now.length, 11);
        expect(now.sublist(0, 8), old.sublist(0, 8));
        expect(now[8], old[7]);
        expect(now.sublist(9), old.sublist(8));
      }
    }
    final text = jsonEncode(after);
    expect(text.contains('"legs"'), isFalse);
    expect(
      checkInvariants(GameState.fromJson(SaveCodec.migrations[3]!(after))),
      isEmpty,
    );
  });

  test('v3 to v4: a camel down with brucellosis is well, its events gone', () {
    final raw = jsonDecode(
      File(fixtures[3]!).readAsStringSync(),
    ) as Map<String, Object?>;
    final data = raw['data']! as Map<String, Object?>;
    final camel =
        ((data['world']! as Map)['camels']! as List).first
            as Map<String, Object?>;
    camel
      ..['health'] = 'sick'
      ..['illness'] = 'brucellosis'
      ..['sickSince'] = 300;
    final inbox = (data['inboxes']! as Map).values.first as List;
    inbox.add({
      'type': 'fellSick',
      'day': 300,
      'owner': camel['owner'],
      'camel': camel['id'],
      'name': camel['name'],
      'illness': 'brucellosis',
    });
    final n = inbox.length;
    final out = SaveCodec.migrations[3]!(data);
    final c = ((out['world']! as Map)['camels']! as List).first as Map;
    expect(c['health'], 'healthy');
    expect(c['illness'], isNull);
    expect(c['sickSince'], isNull);
    expect(((out['inboxes']! as Map).values.first as List).length, n - 1);
    expect(jsonEncode(out).contains('brucellosis'), isFalse);
    expect(checkInvariants(GameState.fromJson(out)), isEmpty);
  });

  group('rejects without losing anything', () {
    test('garbage', () {
      expect(codec.decode('not json'), isA<LoadFailed>());
      expect(codec.decode('{"a":1}'), isA<LoadFailed>());
    });

    test('a save from a newer app', () {
      final r = codec.decode(
        jsonEncode({
          'format': SaveCodec.format,
          'version': SaveCodec.currentVersion + 1,
          'data': <String, Object?>{},
        }),
      ) as LoadFailed;
      expect(r.problem, LoadProblem.tooNew);
    });

    test('broken data inside a valid envelope', () {
      final r = codec.decode(
        jsonEncode({
          'format': SaveCodec.format,
          'version': SaveCodec.currentVersion,
          'data': {'world': 1},
        }),
      ) as LoadFailed;
      expect(r.problem, LoadProblem.corrupt);
    });
  });

  group('SaveStore', () {
    test('a broken save is backed up and never overwritten', () async {
      final backend = MemoryBackend()..data['marah.save'] = '{broken';
      final store = SaveStore(backend);
      expect(await store.open(), isA<OpenFailed>());
      expect(backend.data['marah.save.broken'], '{broken');
      await store.save(sampleGame().state);
      await store.flush();
      expect(backend.data['marah.save'], '{broken');
    });

    test('the fallback is the last save proven good, and restores', () async {
      final backend = MemoryBackend();
      final store = SaveStore(backend);
      final g = sampleGame();
      await store.save(g.state);
      expect(backend.data['marah.save.prev'], isNull);
      final good = backend.data['marah.save'];
      final opened = SaveStore(backend);
      expect(await opened.open(), isA<Opened>());
      // Only a save the engine proved good becomes the fallback.
      expect(backend.data['marah.save.prev'], isNull);
      expect(await opened.markGood(), isTrue);
      expect(backend.data['marah.save.prev'], good);

      backend.data['marah.save'] = '{broken';
      final again = SaveStore(backend);
      expect(await again.open(), isA<OpenFailed>());
      final restored = await again.openPrevious() as Opened;
      expect(restored.state.world.day, g.today);
      expect(backend.data['marah.save'], good);
      expect(again.locked, isFalse);
    });

    test('one failed write does not stop later writes', () async {
      final backend = _FlakyBackend();
      final store = SaveStore(backend);
      final g = sampleGame();
      backend.failNext = true;
      await expectLater(store.save(g.state), throwsA(isA<StateError>()));
      await store.save(g.state);
      await store.flush();
      expect(backend.data['marah.save'], isNotNull);
    });

    test('unreadable bytes are backed up and saving is locked', () async {
      final backend = _FlakyBackend()..data['marah.save'] = 'x';
      backend.failReads = true;
      final store = SaveStore(backend);
      expect(await store.open(), isA<OpenFailed>());
      expect(backend.data['marah.save.broken'], 'x');
      await store.save(sampleGame().state);
      expect(backend.data['marah.save'], 'x');
    });

    test('start over clears the slot but keeps the broken backup', () async {
      final backend = MemoryBackend()..data['marah.save'] = '{broken';
      final store = SaveStore(backend);
      await store.open();
      await store.startOver();
      expect(await store.open(), isA<NoSave>());
      expect(backend.data['marah.save.broken'], '{broken');
      await store.save(sampleGame().state);
      await store.flush();
      expect(await store.open(), isA<Opened>());
    });
  });
}

class _FlakyBackend extends MemoryBackend {
  bool failNext = false;
  bool failReads = false;

  @override
  Future<void> write(String key, String value) async {
    if (failNext) {
      failNext = false;
      throw StateError('disk full');
    }
    await super.write(key, value);
  }

  @override
  Future<String?> read(String key) async {
    if (failReads) throw const FormatException('bad utf-8');
    return super.read(key);
  }
}
