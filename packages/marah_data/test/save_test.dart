Game sampleGame() {
  final g = Game.create(
    seed: 1,
    playerName: 'اختبار',
    farmName: 'عزبة الاختبار',
    region: Region.hail,
    favourite: ColorCategory.wodh,
    startedAt: DateTime.utc(2026, 11, 8),
  );
  final bot = Bot(g);
  for (var i = 0; i < 8; i++) {
    bot.week();
  }
  return g;
}

/// Saves written by released versions. They must load forever: if this
/// test fails, add a migration instead of editing the fixture.
/// (Before the first public release the v1 fixture may still be
/// regenerated by deleting it; see docs/adr/0003-save-format.md.)
const fixtures = {
  1: 'test/fixtures/save_v1.json',
  2: 'test/fixtures/save_v2.json',
  3: 'test/fixtures/save_v3.json',
  4: 'test/fixtures/save_v4.json',
};

void main() {
  const codec = SaveCodec();

  test('round trip is exact', () {
    final g = sampleGame();
    final text = codec.encode(g.state, savedAt: DateTime.utc(2026));
    final loaded = codec.decode(text) as Loaded;
    expect(jsonEncode(loaded.state.toJson()), jsonEncode(g.state.toJson()));
  });

  for (final MapEntry(key: version, value: path) in fixtures.entries) {
    test('save written by version $version still loads', () {
      final file = File(path);
      if (!file.existsSync()) {
        // Fixtures are created on purpose only, never by a passing test.
        if (Platform.environment['MARAH_WRITE_FIXTURES'] != '1') {
          fail(
            'missing fixture $path (set MARAH_WRITE_FIXTURES=1 to create '
            'one for the current version)',
          );
        }
        if (version != SaveCodec.currentVersion) {
          fail('missing fixture for old version $version');
        }
        file
          ..createSync(recursive: true)
          ..writeAsStringSync(
            codec.encode(sampleGame().state, savedAt: DateTime.utc(2026)),
          );
      }
      final result = codec.decode(file.readAsStringSync());
      expect(result, isA<Loaded>(), reason: '$result');
      final state = (result as Loaded).state;
      expect(checkInvariants(state), isEmpty);
      // It must still play.
      final g = Game(state)..advanceDays(30);
      expect(checkInvariants(g.state), isEmpty);
    });
  }

  test(
    'v1 to v2: مغاتير becomes وضح, حق and لقي swap, mature becomes فاطر',
    () {
      final raw = jsonDecode(
        File(fixtures[1]!).readAsStringSync(),
      ) as Map<String, Object?>;
      final before = jsonEncode(raw['data']);
      final after = jsonEncode(
        SaveCodec.migrations[1]!(raw['data']! as Map<String, Object?>),
      );
      int n(String text, String pattern) => pattern.allMatches(text).length;
      expect(n(before, '"cat":"maghateer"'), greaterThan(0));
      expect(after.contains('maghateer'), isFalse);
      // the rounds merged into their وضح twins (the next test) are left out
      // of the counts
      final kept = {
        for (final m in RegExp(r'"id":"(r-[^"]+)"').allMatches(after))
          m.group(1),
      };
      final dropped = RegExp(
        r'\{"id":"(r-[^"]+)","cat":"maghateer","sex":"\w+","age":"(\w+)"',
      ).allMatches(before).where((m) => !kept.contains(m.group(1))).toList();
      int droppedAge(String a) => dropped.where((m) => m.group(2) == a).length;
      expect(
        n(after, '"cat":"wodh"'),
        n(before, '"cat":"wodh"') +
            n(before, '"cat":"maghateer"') -
            dropped.length,
      );
      expect(
        n(after, '"age":"haq"'),
        n(before, '"age":"laqi"') - droppedAge('laqi'),
      );
      expect(
        n(after, '"age":"laqi"'),
        n(before, '"age":"haq"') - droppedAge('haq'),
      );
      expect(
        n(after, '"age":"fater"'),
        n(before, '"age":"mature"') - droppedAge('mature'),
      );
      expect(after.contains('"age":"mature"'), isFalse);
      // ledger categories (also under "cat") are left alone
      expect(n(after, '"cat":"feed"'), n(before, '"cat":"feed"'));
    },
  );

  test(
    'v1 to v2: a وضح round is never duplicated, entries and references kept',
    () {
      final raw = jsonDecode(
        File(fixtures[1]!).readAsStringSync(),
      ) as Map<String, Object?>;
      final before = raw['data']! as Map<String, Object?>;
      List<Map<String, Object?>> rounds(Map<String, Object?> d) => [
        for (final f in (d['world']! as Map)['festivals']! as List)
          for (final r in (f as Map)['rounds']! as List)
            r as Map<String, Object?>,
      ];
      int entries(Map<String, Object?> d) =>
          rounds(d).fold(0, (n, r) => n + (r['entries']! as List).length);
      final n0 = entries(before);
      final after = SaveCodec.migrations[1]!(
        jsonDecode(jsonEncode(before)) as Map<String, Object?>,
      );
      for (final f in (after['world']! as Map)['festivals']! as List) {
        final open = [
          for (final r in (f as Map)['rounds']! as List)
            if ((r as Map)['results'] == null)
              '${r['cat']}/${r['sex']}/${r['age']}',
        ];
        expect(open.toSet().length, open.length, reason: '${f['id']}');
      }
      expect(entries(after), n0);
      // every reference to a round names one that exists
      final ids = {for (final r in rounds(after)) r['id']};
      final text = jsonEncode(after);
      for (final m in RegExp(r'"round":"([^"]+)"').allMatches(text)) {
        expect(ids.contains(m.group(1)), isTrue, reason: m.group(1));
      }
      // decoded by today's classes after the later steps too
      final state = GameState.fromJson(
        SaveCodec.migrations[3]!(SaveCodec.migrations[2]!(after)),
      );
      expect(checkInvariants(state), isEmpty);
    },
  );

  test(
    'v1 to v2: a merge moves the entries and the references, within the limit',
    () {
      Map<String, Object?> v1() =>
          (jsonDecode(File(fixtures[1]!).readAsStringSync())
                  as Map<String, Object?>)['data']!
              as Map<String, Object?>;
      // an open مغاتير round and its open وضح twin in the fixture
      (Map<String, Object?>, Map<String, Object?>) pair(
        Map<String, Object?> d,
      ) {
        for (final f in (d['world']! as Map)['festivals']! as List) {
          final rs = ((f as Map)['rounds']! as List)
              .cast<Map<String, Object?>>();
          for (final m in rs) {
            if (m['cat'] != 'maghateer' || m['results'] != null) continue;
            for (final t in rs) {
              if (t['cat'] == 'wodh' &&
                  t['sex'] == m['sex'] &&
                  t['age'] == m['age'] &&
                  t['results'] == null) {
                return (m, t);
              }
            }
          }
        }
        throw StateError('no pair in the fixture');
      }

      Map<String, Object?> entry(String camel) => {
        'camel': camel,
        'owner': 'p',
      };
      List<Map<String, Object?>> roundsOf(Map<String, Object?> d) => [
        for (final f in (d['world']! as Map)['festivals']! as List)
          for (final r in (f as Map)['rounds']! as List)
            r as Map<String, Object?>,
      ];

      // within the limit: 2 + 1 of one owner's camels, and an event naming the
      // مغاتير round
      var d = v1();
      var (m, t) = pair(d);
      final mid = m['id']! as String, tid = t['id']! as String;
      m['entries'] = [entry('a'), entry('b')];
      t['entries'] = [entry('c')];
      ((d['inboxes']! as Map).values.first as List).add({
        'type': 'entered',
        'day': 1,
        'owner': 'p',
        'camel': 'a',
        'round': mid,
      });
      var out = SaveCodec.migrations[1]!(d);
      var rs = roundsOf(out);
      expect(rs.any((r) => r['id'] == mid), isFalse);
      final twin = rs.firstWhere((r) => r['id'] == tid);
      expect(
        [for (final e in twin['entries']! as List) (e as Map)['camel']],
        ['c', 'a', 'b'],
      );
      expect(jsonEncode(out).contains('"round":"$mid"'), isFalse);
      expect(jsonEncode(out).contains('"round":"$tid"'), isTrue);

      // over the limit (3 + 2 of one owner's camels): the two stay apart
      d = v1();
      (m, t) = pair(d);
      m['entries'] = [entry('a'), entry('b'), entry('c')];
      t['entries'] = [entry('d'), entry('e')];
      out = SaveCodec.migrations[1]!(d);
      rs = roundsOf(out);
      expect(rs.any((r) => r['id'] == m['id']), isTrue);
      expect(
        (rs.firstWhere((r) => r['id'] == m['id'])['entries']! as List).length,
        3,
      );
    },
  );

  test('v1 to v2: favourite, deaths by age and crossbred calves', () {
    final data = <String, Object?>{
      'world': {
        'camels': [
          {'id': 'dam', 'born': 0, 'cat': 'wodh', 'crossbred': false},
          {
            'id': 'calf',
            'born': 100,
            'cat': 'maghateer',
            'crossbred': true,
            'sire': {'id': 'bull', 'name': 'x', 'cat': 'maghateer'},
            'dam': {'id': 'dam', 'name': 'y', 'cat': 'wodh'},
          },
          {
            'id': 'mixed',
            'born': 100,
            'cat': 'homr',
            'crossbred': true,
            'sire': {'id': 'bull', 'name': 'x', 'cat': 'maghateer'},
            'dam': {'id': 'red', 'name': 'z', 'cat': 'homr'},
          },
          {'id': 'old', 'born': 0, 'cat': 'homr', 'crossbred': false},
        ],
        'festivals': <Object?>[],
      },
      'players': [
        {'favourite': 'maghateer'},
      ],
      'inboxes': {
        'p': [
          {'type': 'died', 'day': 365 * 9, 'camel': 'old', 'age': 'mature'},
          {'type': 'died', 'day': 365 * 15, 'camel': 'old', 'age': 'mature'},
          {'type': 'died', 'day': 365 * 22, 'camel': 'old', 'age': 'mature'},
          {'type': 'died', 'day': 365 * 15, 'camel': 'gone', 'age': 'mature'},
          {'type': 'died', 'day': 200, 'camel': 'old', 'age': 'hwar'},
          {'type': 'died', 'day': 100, 'camel': 'old', 'age': 'hwar'},
