    test('save written by version $version still loads', () {
      final file = File(path);
      if (!file.existsSync()) {
        // Fixtures are created on purpose only, never by a passing test.
        if (Platform.environment['MARAH_WRITE_FIXTURES'] != '1') {
          fail(
            'missing fixture $path (set MARAH_WRITE_FIXTURES=1 to create '
            'one for the current version)',
          );
        }
        if (version != SaveCodec.currentVersion) {
          fail('missing fixture for old version $version');
        }
        file
          ..createSync(recursive: true)
          ..writeAsStringSync(
            codec.encode(sampleGame().state, savedAt: DateTime.utc(2026)),
          );
      }
      final result = codec.decode(file.readAsStringSync());
      expect(result, isA<Loaded>(), reason: '$result');
      final state = (result as Loaded).state;
      expect(checkInvariants(state), isEmpty);
      // It must still play.
      final g = Game(state)..advanceDays(30);
      expect(checkInvariants(g.state), isEmpty);
